const { contextBridge, ipcRenderer } = require('electron');

const call = (channel) => (...args) => ipcRenderer.invoke(channel, ...args);

contextBridge.exposeInMainWorld('library', {
  get: call('library:get'),
  rescan: call('library:rescan'),
  launch: call('item:launch'),
  updateItem: call('item:update'),
  removeItem: call('item:remove'),
  addManual: call('item:addManual'),
  openFolder: call('item:openFolder'),
  pickFile: call('dialog:pickFile'),
  pickFolder: call('dialog:pickFolder'),
  createCategory: call('category:create'),
  renameCategory: call('category:rename'),
  deleteCategory: call('category:delete'),
  moveCategory: call('category:move'),
  updateSettings: call('settings:update'),
  coverOptions: call('covers:options'),
  applyCover: call('covers:apply'),
  coverFromFile: call('covers:file'),
  resetCover: call('covers:reset'),
  refetchCovers: call('covers:refetchMissing'),
  openDataFolder: call('app:openDataFolder'),
  toggleFullscreen: call('app:toggleFullscreen'),
  openExternal: call('app:openExternal'),
  copyText: call('app:copyText'),
  getUpdate: call('update:get'),
  checkUpdate: call('update:check'),
  installUpdate: call('update:install'),
  getMedia: call('media:get'),
  mediaCommand: call('media:command'),
  openAppleMusic: call('media:openApp'),
  version: call('app:version'),
  onUpdate: (cb) => ipcRenderer.on('update:state', (_e, s) => cb(s)),
  onMedia: (cb) => ipcRenderer.on('media:state', (_e, s) => cb(s)),
  onChange: (cb) => ipcRenderer.on('library:changed', (_e, snap) => cb(snap)),
  onToast: (cb) => ipcRenderer.on('toast', (_e, t) => cb(t)),
  onFullscreen: (cb) => ipcRenderer.on('fullscreen', (_e, v) => cb(v)),
});
